[NeoRpcService("boot", Version = 1)]
internal sealed class BootService
{
    private readonly string? _epoch;
    private readonly bool _commandReview;
    private readonly bool _userInput;
    private readonly bool _developer;
    internal BootService() { }
    internal BootService(string epoch) { _epoch = epoch; }
    internal BootService(string epoch, bool commandReview) { _epoch = epoch; _commandReview = commandReview; }
    internal BootService(string epoch, bool commandReview, bool userInput) : this(epoch, commandReview) { _userInput = userInput; }
    internal BootService(string epoch, bool commandReview, bool userInput, bool developer) : this(epoch, commandReview, userInput) { _developer = developer; }
    /// <summary>
    /// Receives the theme the window shows, so the next start can paint the window in its background before
    /// any page exists. Null when this host keeps no appearance.
    /// </summary>
    internal Action<DesktopAppearance>? RememberAppearance { get; init; }

    /// <summary>
    /// True while the window repairs a configuration file that cannot be loaded: there is no host yet, and the
    /// page shows the <c>startupConfig</c> editor instead of the workspace.
    /// </summary>
    internal bool ConfigRecovery { get; init; }

    /// <summary>True when the application started without any enabled model provider.</summary>
    internal bool ProviderSetup { get; init; }

    /// <summary>True for the developer instance, for a window that has no host.</summary>
    internal bool Developer { get; init; }

    /// <summary>Whether the host is closing: the page says so, and offers to end the process when the close lasts.</summary>
    internal DesktopClosing? Closing { get; init; }

    /// <summary>Remembers the window's theme and background for the next start.</summary>
    [NeoRpcMethod("appearance")]
    public BootAppearanceResponse Appearance(BootAppearanceRequest request)
    {
        if (!DesktopAppearance.TryCreate(request?.Theme, request?.Background, out var appearance)) return new("invalid_request");
        if (RememberAppearance is null) return new("unavailable");
        RememberAppearance(appearance);
        return new("ok");
    }

    /// <summary>The most reports of the page the log takes in a minute: a page that loops cannot fill the log.</summary>
    internal const int ReportsPerMinute = 60;

    /// <summary>The longest report written; longer ones are cut.</summary>
    internal const int ReportLength = 1024;

    private readonly Lock _reports = new();
    private DateTimeOffset _reportWindow = DateTimeOffset.MinValue;
    private int _reportCount;

    /// <summary>The clock of the reports; its tests choose it.</summary>
    internal TimeProvider Clock { get; init; } = TimeProvider.System;

    /// <summary>
    /// Writes what the page noticed to the log of the application (logger <c>CodeAlta.Desktop.Page</c>): a call that
    /// waited long, a host that did not answer for a while. The page cannot write files; without this its observations
    /// stay in its console, which nobody reads after the fact. Answers <c>ok</c>, <c>invalid_request</c>, or
    /// <c>limited</c> beyond <see cref="ReportsPerMinute"/> reports in a minute.
    /// </summary>
    [NeoRpcMethod("report")]
    public BootReportResponse Report(BootReportRequest request)
    {
        if (request?.Message is not { Length: > 0 } message || request.Level is not ("warning" or "information")) return new("invalid_request");
        lock (_reports)
        {
            var now = Clock.GetUtcNow();
            if (now - _reportWindow >= TimeSpan.FromMinutes(1)) { _reportWindow = now; _reportCount = 0; }
            if (++_reportCount > ReportsPerMinute) return new("limited");
        }

        var text = Clean(message);
        var logger = LogManager.GetLogger("CodeAlta.Desktop.Page");
        if (request.Level == "warning") logger.Warn(text);
        else logger.Info(text);
        return new("ok");

        // One line, bounded, without control characters: what the page sends cannot forge other lines of the log.
        static string Clean(string value)
        {
            var length = Math.Min(value.Length, ReportLength);
            return string.Create(length, value, static (span, source) =>
            {
                for (var index = 0; index < span.Length; index++) span[index] = char.IsControl(source[index]) ? ' ' : source[index];
            });
        }
    }

    [NeoRpcMethod("status")]
    public BootStatus Status(BootRequest request) => ConfigRecovery
        ? new("config-recovery", "CodeAlta", DesktopCommandLine.Version, false) { ConfigRecovery = true, DeveloperMode = Developer || _developer }
        : _epoch is null
        ? new("in-development", "CodeAlta", DesktopCommandLine.Version, false)
        : new("owned-text-only", "CodeAlta", DesktopCommandLine.Version, true) { HostEpoch = _epoch, CommandReviewEnabled = _commandReview, OwnedAsksEnabled = true, OwnedUserInputEnabled = _userInput, DeveloperMode = Developer || _developer, ProviderSetup = ProviderSetup, Closing = Closing?.Snapshot() };
}

internal sealed record BootRequest;

/// <summary>What the page reports to the log: <c>warning</c> or <c>information</c>, and its text.</summary>
internal sealed record BootReportRequest(string? Level, string? Message);

/// <summary><c>ok</c>, <c>invalid_request</c> or <c>limited</c>.</summary>
internal sealed record BootReportResponse(string Status);

/// <summary>The window's theme (<c>dark</c> or <c>light</c>) and its background as <c>#rrggbb</c>.</summary>
internal sealed record BootAppearanceRequest(string? Theme, string? Background);

/// <summary><c>ok</c>, <c>invalid_request</c>, or <c>unavailable</c> when the host keeps no appearance.</summary>
internal sealed record BootAppearanceResponse(string Status);
internal sealed record BootStatus(string State, string ProductName, string Version, bool HostAvailable)
{
    public string? HostEpoch { get; init; }
    public bool CommandReviewEnabled { get; init; }
    public bool OwnedAsksEnabled { get; init; }
    public bool OwnedUserInputEnabled { get; init; }

    /// <summary>True for the developer instance, which runs beside the normal one with its own sessions.</summary>
    public bool DeveloperMode { get; init; }

    /// <summary>True while the configuration file is being repaired; the page then shows only its editor.</summary>
    public bool ConfigRecovery { get; init; }

    /// <summary>
    /// True when the application started without any enabled model provider (a first start, usually): the
    /// page opens the provider settings and guides through them, as the terminal application opens its own.
    /// </summary>
    public bool ProviderSetup { get; init; }

    /// <summary>
    /// Set while the host closes: its services stop one after the other and the window stays until the close ends.
    /// </summary>
    public BootClosing? Closing { get; init; }
}

/// <summary>
/// A host that closes: the step of its close it waits for (<c>sessions</c>, <c>providers</c>, <c>host</c>...), or null
/// before the first one, the seconds since the close was asked for, and whether the page may end the process.
/// </summary>
internal sealed record BootClosing(string? Step, int Seconds, bool CanForceExit);

