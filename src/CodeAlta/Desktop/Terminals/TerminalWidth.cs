    /// <summary>The columns of a character: 0 for one that joins the character before it, 2 for a wide one, 1 otherwise.</summary>
    internal static int Of(int codePoint)
    {
        if (codePoint < 0x300) return 1;
        if (codePoint is 0x200B or 0x200C or 0x200D or 0x2060 or 0xFEFF || codePoint is >= 0xFE00 and <= 0xFE0F || codePoint is >= 0xE0100 and <= 0xE01EF) return 0;
        if (Rune.IsValid(codePoint) && Rune.GetUnicodeCategory(new Rune(codePoint)) is UnicodeCategory.NonSpacingMark or UnicodeCategory.EnclosingMark) return 0;
        // The last pair that starts at or before the character holds it, or none does.
        int low = 0, high = Wide.Length / 2 - 1;
        while (low <= high)
        {
            var middle = (low + high) / 2;
            if (codePoint < Wide[middle * 2]) high = middle - 1;
            else if (codePoint > Wide[middle * 2 + 1]) low = middle + 1;
            else return 2;
        }
        return 1;
    }
